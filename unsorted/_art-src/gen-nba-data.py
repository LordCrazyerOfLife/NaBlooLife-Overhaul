"""Builds nba-data.js from nba/jugadores.txt (rosters, coaches) + nba/logos.  Run: python _art-src/gen-nba-data.py"""
import re, json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
txt = open(os.path.join(root, "nba", "jugadores.txt"), encoding="utf-8").read().splitlines()
CONF = {
    "E": "ATL BKN BOS CHA CHI CLE DET IND MIA MIL NY ORL PHI TOR WSH".split(),
    "W": "DAL DEN GS HOU LAC LAL MEM MIN NO OKC PHX POR SAC SA UTAH".split(),
}
DIV = {
    "Atlantic": "BOS BKN NY PHI TOR", "Central": "CHI CLE DET IND MIL", "Southeast": "ATL CHA MIA ORL WSH",
    "Northwest": "DEN MIN OKC POR UTAH", "Pacific": "GS LAC LAL PHX SAC", "Southwest": "DAL HOU MEM NO SA",
}
REP = dict(OKC=92, SA=88, DEN=86, HOU=85, NY=85, CLE=84, DET=82, BOS=82, MIN=82, LAL=80, ORL=78, ATL=76, MIA=74, PHI=76,
           GS=77, MIL=74, DAL=72, LAC=72, TOR=72, PHX=70, MEM=70, IND=70, NO=62, SAC=62, POR=66, CHI=58, CHA=62, BKN=52,
           UTAH=52, WSH=52)
teams = []
cur = None
pl = re.compile(r"^(\d+|-)\s+(.+?)\s{2,}([GFC](?:-[GFC])?)\s+(\d+)\s+(\d+' \d+\")\s+(\d+) lbs\s+(.*)$")
for i, ln in enumerate(txt):
    m = re.match(r"^(.+) \(([A-Z]+)\)$", ln.strip())
    if m and i + 1 < len(txt) and txt[i - 1].startswith("====") if i else False:
        cur = {"abbr": m.group(2), "name": m.group(1), "coach": "", "players": []}
        teams.append(cur)
        continue
    if not cur:
        continue
    if ln.startswith("Entrenador:"):
        cur["coach"] = ln.split(":", 1)[1].strip()
        continue
    p = pl.match(ln.strip())
    if p:
        info = p.group(7).strip()
        college, exp = "", info
        if "/" in info:
            college, exp = [x.strip() for x in info.split("/", 1)]
        rookie = "rookie" in exp
        yrs = 0 if rookie else int((re.search(r"(\d+)", exp) or [0, 0])[1] if re.search(r"(\d+)", exp) else 0)
        cur["players"].append({"n": p.group(2).strip(), "pos": p.group(3), "age": int(p.group(4)), "ht": p.group(5), "num": p.group(1), "col": college, "yrs": yrs})
out = []
for t in teams:
    a = t["abbr"]
    conf = "E" if a in CONF["E"] else "W"
    div = next(d for d, v in DIV.items() if a in v.split())
    logo = f"nba/logos/{a}.png"
    assert os.path.exists(os.path.join(root, logo)), logo
    out.append({"abbr": a, "name": t["name"], "coach": t["coach"], "conf": conf, "div": div, "rep": REP.get(a, 65), "logo": logo, "players": t["players"]})
assert len(out) == 30, len(out)
open(os.path.join(root, "nba-data.js"), "w", encoding="utf-8").write("/* Generated by _art-src/gen-nba-data.py - do not edit by hand. */\nwindow.FL_NBA_DATA = " + json.dumps({"teams": out}, ensure_ascii=False) + ";\n")
print(len(out), sum(len(t["players"]) for t in out))
