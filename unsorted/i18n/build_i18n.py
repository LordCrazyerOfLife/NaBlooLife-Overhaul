"""Builds the dictionaries the game loads:
  ui.tsv + rules.tsv -> es.js / pt.js            (hand-made UI strings and regex rules)
  events.tsv          -> es.events.js / pt.events.js  (bulk event/log text, templates with {tokens})
Run from anywhere: python build_i18n.py
"""
import collections, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
LANGS = {"es": 1, "pt": 2}
TOK = re.compile(r"\{[^{}\s]+\}")


def rows(name):
    path = os.path.join(HERE, name)
    if not os.path.exists(path):
        return
    for n, line in enumerate(open(path, encoding="utf-8"), 1):
        line = line.rstrip("\n")
        if not line.strip() or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) != 3:
            raise SystemExit(f"{name}:{n}: expected 3 tab-separated columns, got {len(cols)}: {line!r}")
        yield n, cols


def write(fname, code, payload):
    body = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    with open(os.path.join(HERE, fname), "w", encoding="utf-8") as f:
        f.write(f"/* generated by build_i18n.py - edit the .tsv files instead */\nFL_I18N.add({json.dumps(code)},{body});\n")


def safe_words(en):
    """Lowercase words of the literal text that are not glued to a {token} (so they appear as-is at runtime)."""
    parts = TOK.split(en)
    out = []
    for i, seg in enumerate(parts):
        ws = list(re.finditer(r"[a-z']+", seg.lower()))
        for j, m in enumerate(ws):
            glued_left = i > 0 and m.start() == 0
            glued_right = i < len(parts) - 1 and m.end() == len(seg)
            if not (glued_left or glued_right):
                out.append(m.group(0))
    return out


# ---- UI ----
for code, col in LANGS.items():
    exact, seen = {}, {}
    for n, c in rows("ui.tsv"):
        key, val = c[0].strip(), c[col].strip()
        k = key.lower()
        if k in seen and seen[k][1].lower() != val.lower():
            print(f"warning [{code}]: ui.tsv:{n} {key!r} conflicts with line {seen[k][0]}; first one wins")
            continue
        seen[k] = (n, val)
        exact[key] = val
    rules = [[c[0], c[col]] for _, c in rows("rules.tsv")]
    write(f"{code}.js", code, {"exact": exact, "re": rules})
    print(f"{code}.js: {len(exact)} strings, {len(rules)} rules")

# ---- events ----
ev = list(rows("events.tsv") or [])
if ev:
    freq = collections.Counter(w for _, c in ev for w in set(safe_words(c[0])))
    for code, col in LANGS.items():
        exact, tpl, skipped = {}, [], 0
        for n, c in ev:
            en, tr = c[0].strip(), c[col].strip()
            if not tr:
                continue
            if not TOK.search(en):
                exact[en] = tr
                continue
            # starts with a literal word that isn't glued to the first {token} -> index by that first word
            lead = TOK.split(en)[0]
            first = re.match(r"[^A-Za-z]*([A-Za-z']+)", lead)
            if first and first.end() < len(lead):
                tpl.append([en, tr, first.group(1).lower(), 1])
                continue
            words = safe_words(en)
            if not words:
                skipped += 1  # pure "{1} {2}" style templates can't be matched safely
                continue
            tpl.append([en, tr, min(words, key=lambda w: (freq[w], -len(w))), 0])
        for _, c in rows("glossary.tsv") or []:  # valores sueltos que mete el juego (man, boy, cop...)
            exact.setdefault(c[0].strip(), c[col].strip())
        write(f"{code}.events.js", code, {"exact": exact, "tpl": tpl, "weak": 1})
        print(f"{code}.events.js: {len(exact)} strings, {len(tpl)} templates, {skipped} skipped")
